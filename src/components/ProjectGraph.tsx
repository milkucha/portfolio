"use client";

import { useEffect, useLayoutEffect, useRef, useState } from "react";
import type { CSSProperties, KeyboardEvent, PointerEvent } from "react";
import {
  forceCollide,
  forceLink,
  forceManyBody,
  forceSimulation,
  forceX,
  forceY,
  type Simulation,
  type SimulationLinkDatum,
  type SimulationNodeDatum,
} from "d3-force";
import graphData from "@/data/graph.json";
import { projects } from "@/data/projects";
import type { VaultGraph, VaultNode } from "@/data/types";
import { GraphCard } from "./GraphCard";

/*
 * A replica of the Obsidian graph view, restricted to the featured projects and the vault notes
 * around them (src/data/graph.json, generated by scripts/build-graph.mjs).
 *
 * Performance (see .claude/skills/fixing-motion-performance):
 * - Flat circles in HTML over hairline SVG links. d3 ticks write transforms and line endpoints
 *   straight to the DOM; React renders only on hover/pin/resize.
 * - The simulation stops at alphaMin, and while the graph is off-screen or the tab is hidden.
 * - Only opacity transitions (dimming, label fade-in). No filters, no continuous animation.
 * - prefers-reduced-motion: the layout is computed synchronously and nothing fades.
 */

/**
 * Force settings from the vault's .obsidian/graph.json, mapped onto d3-force:
 * - centerStrength -> forceX/forceY strength
 * - repelStrength  -> forceManyBody strength (x REPEL_SCALE, negative)
 * - linkStrength   -> forceLink strength, times d3's default 1/min(degree) so hubs don't over-pull
 * - linkDistance   -> forceLink distance in px (scaled to the frame)
 * - nodeSizeMultiplier / lineSizeMultiplier -> circle radius / link stroke width
 */
const OBSIDIAN = {
  centerStrength: 0.111471956464496,
  repelStrength: 14.810463515374,
  linkStrength: 0.76310014921443,
  linkDistance: 83,
  nodeSizeMultiplier: 1.35,
  lineSizeMultiplier: 0.839216404247528,
};
const REPEL_SCALE = 22;

const graph = graphData as VaultGraph;
const nodes = graph.nodes;
const indexById = new Map(nodes.map((n, i) => [n.id, i] as const));
const linkEnds = graph.links.map((l) => [indexById.get(l.source)!, indexById.get(l.target)!] as const);
const neighbours = nodes.map((n) => new Set([n.id]));
for (const [s, t] of linkEnds) {
  neighbours[s].add(nodes[t].id);
  neighbours[t].add(nodes[s].id);
}
const projectById = new Map(projects.map((p) => [p.id, p]));

/** md+ only: the details card docks top-right (16px inset + 320px wide) plus a gap. */
const CARD_RESERVE = 16 + 320 + 32;
const freeWidthFor = (w: number) => (w >= 768 ? w - CARD_RESERVE : w);

/** Obsidian-style base radius: grows with the square root of the node's link count. */
const baseRadius = (n: VaultNode) => OBSIDIAN.nodeSizeMultiplier * (1.6 + 1.25 * Math.sqrt(n.degree));
/** Projects are drawn 5x the Obsidian size, every other note at half, so the four projects
 *  read as the landmarks. Projects shrink with the frame on phones so they still fit. */
const PROJECT_SCALE = 5;
const NOTE_SCALE = 0.5;
const radiusFor = (n: VaultNode, s: number) =>
  n.kind === "project"
    ? baseRadius(n) * PROJECT_SCALE * Math.max(0.5, Math.min(1, s))
    : baseRadius(n) * NOTE_SCALE * Math.max(0.8, Math.min(1, s));

/** Pointer target (invisible circle): the project disc itself plus a margin, and at least
 *  24px across for the small dots. */
const hitFor = (n: VaultNode, r: number) => (n.kind === "project" ? r + 4 : Math.max(12, r + 6));

/** Space kept below a project for its label, which sits outside the disc. */
const PROJECT_LABEL_GAP = 20;

/** Colours: the vault's graph colorGroups, per category tag (see globals.css --og-*). */
const colorFor = (n: VaultNode) =>
  n.kind === "project" ? "var(--og-project)" : `var(--og-${n.tag ?? "concept"})`;

interface SimNode extends SimulationNodeDatum {
  id: string;
}

function usePrefersReducedMotion(): boolean {
  const [reduced, setReduced] = useState(false);
  useEffect(() => {
    const mq = window.matchMedia("(prefers-reduced-motion: reduce)");
    const update = () => setReduced(mq.matches);
    mq.addEventListener("change", update);
    const id = requestAnimationFrame(update);
    return () => {
      cancelAnimationFrame(id);
      mq.removeEventListener("change", update);
    };
  }, []);
  return reduced;
}

export function ProjectGraph() {
  const containerRef = useRef<HTMLDivElement>(null);
  const simRef = useRef<Simulation<SimNode, SimulationLinkDatum<SimNode>> | null>(null);
  const simNodesRef = useRef<SimNode[]>([]);
  const nodeEls = useRef<(HTMLDivElement | null)[]>([]);
  const lineEls = useRef<(SVGLineElement | null)[]>([]);
  const litEls = useRef<(SVGLineElement | null)[]>([]);
  const visibleRef = useRef(false);
  const dragRef = useRef<{ i: number; pointerId: number; x0: number; y0: number; moved: boolean } | null>(null);

  const [size, setSize] = useState<{ w: number; h: number } | null>(null);
  const [hovered, setHovered] = useState<string | null>(null);
  const [pinned, setPinned] = useState<string | null>(null);
  const reducedMotion = usePrefersReducedMotion();

  // Frame scale: forces and sizes are tuned for a ~640px square and shrink on phones.
  const scale = size ? Math.max(0.5, Math.min(1.1, Math.min(freeWidthFor(size.w), size.h) / 640)) : 1;
  const radii = nodes.map((n) => radiusFor(n, scale));

  /** Write simulation positions straight to the DOM (no React render). */
  const applyPositions = () => {
    const sn = simNodesRef.current;
    if (!sn.length) return;
    for (let i = 0; i < sn.length; i++) {
      const el = nodeEls.current[i];
      if (el) el.style.transform = `translate(${sn[i].x ?? 0}px, ${sn[i].y ?? 0}px)`;
    }
    for (let li = 0; li < linkEnds.length; li++) {
      const a = sn[linkEnds[li][0]];
      const b = sn[linkEnds[li][1]];
      const base = lineEls.current[li];
      if (base) setLine(base, a, b);
      const lit = litEls.current[li];
      if (lit) setLine(lit, a, b);
    }
  };
  const applyRef = useRef(applyPositions);
  useLayoutEffect(() => {
    applyRef.current = applyPositions;
    // After every render (hover, pin, resize), re-apply positions so React never owns them.
    applyPositions();
  });

  // Measure the container.
  useEffect(() => {
    const el = containerRef.current;
    if (!el) return;
    const ro = new ResizeObserver(([entry]) => {
      const { width, height } = entry.contentRect;
      if (width > 0 && height > 0) setSize({ w: Math.round(width), h: Math.round(height) });
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, []);

  // Create / reconfigure the simulation on size (or motion preference) change. Layout effect, so
  // the first positions land before the first paint.
  useLayoutEffect(() => {
    if (!size) return;
    const { w, h } = size;
    const freeW = freeWidthFor(w);
    const cx = freeW / 2;
    const cy = h / 2;
    const rs = nodes.map((n) => radiusFor(n, scale));

    let fresh = false;
    if (!simRef.current) {
      // Deterministic phyllotaxis seed (d3's own initial layout), centred in the free area.
      simNodesRef.current = nodes.map((n, i) => {
        const rad = 9 * scale * Math.sqrt(0.5 + i);
        const a = i * Math.PI * (3 - Math.sqrt(5));
        return { id: n.id, x: cx + rad * Math.cos(a), y: cy + rad * Math.sin(a) };
      });
      simRef.current = forceSimulation<SimNode>(simNodesRef.current).stop();
      fresh = true;
    }
    const sim = simRef.current;
    const sn = simNodesRef.current;
    const deg = nodes.map((n) => Math.max(1, n.degree));
    // Wide frames: pull a little harder vertically so the cloud fills the width, like Obsidian's
    // pane does, without spilling off the top and bottom.
    const aspect = Math.max(1, freeW / h);

    const isProject = nodes.map((n) => n.kind === "project");
    sim
      .force(
        "link",
        forceLink<SimNode, SimulationLinkDatum<SimNode>>(linkEnds.map(([s, t]) => ({ source: s, target: t })))
          // Measured edge to edge, so the big project discs keep the same gap to their notes as
          // two small dots would (plus a little extra room for the project's label).
          .distance((l) => {
            const a = (l.source as SimNode).index!;
            const b = (l.target as SimNode).index!;
            return OBSIDIAN.linkDistance * scale + rs[a] + rs[b] + (isProject[a] || isProject[b] ? 8 * scale : 0);
          })
          .strength(
            (l) =>
              OBSIDIAN.linkStrength /
              Math.min(deg[(l.source as SimNode).index!], deg[(l.target as SimNode).index!]),
          ),
      )
      .force(
        "charge",
        // Projects push harder, in proportion to their size, so they spread apart instead of
        // clumping in the middle; the small notes keep Obsidian's repel.
        forceManyBody<SimNode>()
          .strength((_, i) => -OBSIDIAN.repelStrength * REPEL_SCALE * scale * (isProject[i] ? 4 : 1))
          .distanceMax(460 * scale),
      )
      .force(
        "collide",
        forceCollide<SimNode>((_, i) => (isProject[i] ? rs[i] + 14 * scale : rs[i] + 3)).iterations(2),
      )
      .force("x", forceX<SimNode>(cx).strength(OBSIDIAN.centerStrength / aspect))
      .force("y", forceY<SimNode>(cy).strength(OBSIDIAN.centerStrength * Math.min(1.6, aspect)))
      .velocityDecay(0.45);

    // Backstop: keep every dot inside the frame (wider side margin on phones, for the labels).
    const sideGap = freeW < 640 ? 22 : 6;
    const clamp = () => {
      for (let i = 0; i < sn.length; i++) {
        const m = rs[i] + 6;
        const mb = m + (isProject[i] ? PROJECT_LABEL_GAP : 0);
        const mx = isProject[i] ? rs[i] + 6 : rs[i] + sideGap;
        sn[i].x = Math.max(mx, Math.min(freeW - mx, sn[i].x ?? cx));
        sn[i].y = Math.max(m, Math.min(h - mb, sn[i].y ?? cy));
      }
    };

    if (reducedMotion) {
      sim.on("tick", null).stop().alpha(1);
      for (let i = 0; i < 300; i++) {
        sim.tick();
        clamp();
      }
      applyRef.current();
      return;
    }

    // Pre-settle off-screen so the visible part is a short, calm drift into place, not a burst.
    if (fresh) {
      sim.alpha(1);
      for (let i = 0; i < 70; i++) {
        sim.tick();
        clamp();
      }
    } else {
      sim.alpha(Math.max(sim.alpha(), 0.3));
    }
    sim.on("tick", () => {
      clamp();
      applyRef.current();
    });
    clamp();
    applyRef.current();
    if (visibleRef.current) sim.restart();
    return () => {
      sim.stop();
    };
  }, [size, scale, reducedMotion]);

  // Pause while the graph is off-screen or the tab is hidden.
  useEffect(() => {
    const el = containerRef.current;
    if (!el) return;
    let inView = false;
    const update = () => {
      const vis = inView && document.visibilityState === "visible";
      visibleRef.current = vis;
      const sim = simRef.current;
      if (!sim || reducedMotion) return;
      if (!vis) sim.stop();
      else if (sim.alpha() > sim.alphaMin()) sim.restart();
    };
    const io = new IntersectionObserver(([entry]) => {
      inView = entry.isIntersecting;
      update();
    });
    io.observe(el);
    document.addEventListener("visibilitychange", update);
    return () => {
      io.disconnect();
      document.removeEventListener("visibilitychange", update);
    };
  }, [reducedMotion]);

  useEffect(() => () => void simRef.current?.stop(), []);

  // Escape clears a pinned node from anywhere on the page.
  useEffect(() => {
    if (!pinned) return;
    const onKey = (e: globalThis.KeyboardEvent) => {
      if (e.key === "Escape") setPinned(null);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [pinned]);

  // ---- highlight state ---------------------------------------------------------------------

  const active = hovered ?? pinned;
  const ai = active != null ? indexById.get(active) : undefined;
  const activeNode = ai != null ? nodes[ai] : null;
  const projectActive = activeNode?.kind === "project";
  // Projects light up their whole neighbourhood; other dots only their own links and label.
  const lit = ai != null && projectActive ? neighbours[ai] : null;
  const showLabel = (n: VaultNode) => (lit ? lit.has(n.id) : n.id === active);

  // ---- interaction -------------------------------------------------------------------------

  const toLocal = (e: PointerEvent<Element>) => {
    const rect = containerRef.current!.getBoundingClientRect();
    return { x: e.clientX - rect.left, y: e.clientY - rect.top };
  };

  const onPointerDown = (i: number) => (e: PointerEvent<HTMLDivElement>) => {
    if (e.button !== 0) return;
    e.currentTarget.setPointerCapture(e.pointerId);
    const p = toLocal(e);
    dragRef.current = { i, pointerId: e.pointerId, x0: p.x, y0: p.y, moved: false };
  };

  const onPointerMove = (e: PointerEvent<HTMLDivElement>) => {
    const drag = dragRef.current;
    if (!drag || drag.pointerId !== e.pointerId || !size) return;
    const p = toLocal(e);
    if (!drag.moved && Math.hypot(p.x - drag.x0, p.y - drag.y0) < 4) return;
    const n = simNodesRef.current[drag.i];
    const m = radii[drag.i] + 6;
    const x = Math.max(m, Math.min(freeWidthFor(size.w) - m, p.x));
    const y = Math.max(m, Math.min(size.h - m, p.y));
    const sim = simRef.current;
    if (!drag.moved) {
      drag.moved = true;
      // Reheat while dragging so linked neighbours get tugged along, as in Obsidian.
      if (sim && !reducedMotion) sim.alphaTarget(0.3).restart();
    }
    n.fx = x;
    n.fy = y;
    if (reducedMotion) {
      n.x = x;
      n.y = y;
      applyRef.current();
    }
  };

  const onPointerUp = (e: PointerEvent<HTMLDivElement>) => {
    const drag = dragRef.current;
    if (!drag || drag.pointerId !== e.pointerId) return;
    dragRef.current = null;
    const n = simNodesRef.current[drag.i];
    const id = nodes[drag.i].id;
    if (drag.moved) {
      if (reducedMotion) {
        n.x = n.fx ?? n.x;
        n.y = n.fy ?? n.y;
      }
      n.fx = null;
      n.fy = null;
      simRef.current?.alphaTarget(0);
    } else {
      // A tap/click pins the node (the only way to select on touch screens).
      setPinned((cur) => (cur === id ? null : id));
      if (e.pointerType !== "mouse") setHovered(null);
    }
  };

  const onKeyDown = (id: string) => (e: KeyboardEvent<HTMLDivElement>) => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      setPinned((cur) => (cur === id ? null : id));
    } else if (e.key === "Escape") {
      setPinned(null);
      setHovered(null);
      e.currentTarget.blur();
    }
  };

  const cardProject = projectActive ? (projectById.get(activeNode!.id) ?? null) : null;

  return (
    <div className="flex w-full flex-col md:relative">
      <div
        ref={containerRef}
        className="og relative h-[min(68svh,560px)] w-full overflow-hidden md:h-[max(520px,calc(100svh-11rem))]"
        onPointerDown={(e) => {
          if (e.target === e.currentTarget || (e.target as Element).tagName === "svg") setPinned(null);
        }}
      >
        {size && (
          <>
            <svg
              width={size.w}
              height={size.h}
              viewBox={`0 0 ${size.w} ${size.h}`}
              className="absolute inset-0 block select-none"
              aria-hidden="true"
              style={{ ["--og-line-w" as string]: `${OBSIDIAN.lineSizeMultiplier}px` }}
            >
              <g className="og-links" data-dim={lit ? "" : undefined}>
                {linkEnds.map(([s, t], li) => (
                  <line
                    key={`${s}-${t}`}
                    ref={(el) => {
                      lineEls.current[li] = el;
                    }}
                  />
                ))}
              </g>
              {ai != null && (
                // Keyed by the active node, so switching replays the fade-in.
                <g key={active} className="og-links-lit">
                  {linkEnds.map(([s, t], li) =>
                    s === ai || t === ai ? (
                      <line
                        key={`${s}-${t}`}
                        ref={(el) => {
                          litEls.current[li] = el;
                        }}
                      />
                    ) : null,
                  )}
                </g>
              )}
            </svg>
            <div
              role="group"
              aria-label="Graph of projects and the notes they link to in my knowledge base"
              className="pointer-events-none absolute inset-0 select-none"
            >
              {nodes.map((n, i) => {
                const r = radii[i];
                const hit = hitFor(n, r);
                const isProject = n.kind === "project";
                const project = isProject ? projectById.get(n.id) : undefined;
                const style: CSSProperties = {
                  ["--og-c" as string]: colorFor(n),
                  ["--og-r" as string]: `${r}px`,
                  ["--og-hit" as string]: `${hit}px`,
                };
                return (
                  <div
                    key={n.id}
                    ref={(el) => {
                      nodeEls.current[i] = el;
                    }}
                    className="og-node pointer-events-auto absolute left-0 top-0 cursor-grab outline-none active:cursor-grabbing"
                    data-kind={n.kind}
                    data-active={active === n.id || undefined}
                    data-dim={(!!lit && !lit.has(n.id)) || undefined}
                    data-label={showLabel(n) || undefined}
                    style={style}
                    {...(isProject
                      ? {
                          tabIndex: 0,
                          role: "button",
                          "aria-pressed": pinned === n.id,
                          "aria-label": `${project?.name ?? n.label}: ${project?.oneLiner ?? ""}`,
                          onFocus: () => setHovered(n.id),
                          onBlur: () => setHovered(null),
                          onKeyDown: onKeyDown(n.id),
                        }
                      : { "aria-hidden": true })}
                    onPointerEnter={(e) => e.pointerType === "mouse" && setHovered(n.id)}
                    onPointerLeave={(e) => e.pointerType === "mouse" && setHovered(null)}
                    onPointerDown={onPointerDown(i)}
                    onPointerMove={onPointerMove}
                    onPointerUp={onPointerUp}
                    onPointerCancel={onPointerUp}
                  >
                    <span className="og-dot" />
                    <span className="og-label">{n.label}</span>
                  </div>
                );
              })}
            </div>
          </>
        )}
      </div>

      <div className="w-full px-4 pt-4 md:absolute md:right-4 md:top-4 md:w-80 md:p-0">
        <GraphCard project={cardProject} pinned={!!pinned && pinned === active} onClose={() => setPinned(null)} />
      </div>
    </div>
  );
}

function setLine(el: SVGLineElement, a: SimNode, b: SimNode) {
  el.setAttribute("x1", String(a.x ?? 0));
  el.setAttribute("y1", String(a.y ?? 0));
  el.setAttribute("x2", String(b.x ?? 0));
  el.setAttribute("y2", String(b.y ?? 0));
}
